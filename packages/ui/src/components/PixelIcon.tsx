export interface PixelIconProps extends Omit<SVGAttributes<SVGSVGElement>, "viewBox"> {
  name: PixelGlyphName;
  size?: number;
}

export function PixelIcon({ name, size = 24, className, ...rest }: PixelIconProps) {
  const rows = GLYPHS[name];

  return (
    <svg
      viewBox={`0 0 ${GRID} ${GRID}`}
      width={size}
      height={size}
      shapeRendering="crispEdges"
      aria-hidden="true"
      className={className}
      {...rest}
    >
      {rows.flatMap((row, y) =>
        row
          .split("")
          .map((cell, x) => (cell === "1" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill="currentColor" /> : null)),
      )}
    </svg>
  );
}
